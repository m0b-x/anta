#!/usr/bin/env node
'use strict';
/**
 * ANTA PreToolUse guard: the CLAUDE.md non-negotiables that used to rest on
 * instruction alone, checked before the tool runs.
 *
 * Wired from .claude/settings.json for the file tools (Edit, Write,
 * MultiEdit, NotebookEdit) and the shells (Bash, PowerShell). Reads the hook
 * input on stdin; for a call that breaks a rule it prints a PreToolUse deny
 * decision whose reason reaches the model, otherwise it prints nothing.
 * Every path exits 0: a hook error is reported on every later tool call, so
 * a malformed input is a silent allow, never a crash.
 *
 * Rules:
 *  1. Generated Dart is never hand-edited: *.g.dart (build_runner) and
 *     lib/l10n/app_localizations*.dart (gen-l10n), whether through a file
 *     tool or through a shell redirect, copy or write cmdlet aimed at them.
 *  2. No in-place sed or perl (-i): a `perl -i` once emptied an ARB.
 *  3. `dart analyze lib`, never `flutter analyze` on the whole workspace.
 *  4. No sweeping `git add` (-A, --all, -u, `.`): the owner stages named
 *     paths, and a sweep pulls another agent's half-built files into a commit.
 *  5. `flutter test` and `dart test` never in the background: a runner that
 *     hangs on a timed-out test never exits, and the harness waits on it for
 *     hours (2026-10-30). The whole suite takes about four minutes here.
 */

const GENERATED = /(^|[\\/])([^\\/]+\.g\.dart|app_localizations(_[a-z]{2,3})?\.dart)$/i;
const FILE_TOOLS = new Set(['Edit', 'Write', 'MultiEdit', 'NotebookEdit']);
const SHELL_TOOLS = new Set(['Bash', 'PowerShell']);

function exe(name) {
  return new RegExp('(^|[\\\\/])' + name + '(\\.exe|\\.bat|\\.cmd)?$', 'i');
}
const SED_OR_PERL = exe('(sed|gsed|perl)');
const FLUTTER = exe('flutter');
const FLUTTER_OR_DART = exe('(flutter|dart)');
const GIT = exe('git');

function stripQuotes(token) {
  return token.replace(/^["'`]+/, '').replace(/["'`]+$/, '');
}

function generatedReason(path) {
  if (/app_localizations/i.test(path)) {
    return path + ' is generated by gen-l10n. Edit app_en.arb, app_de.arb and app_ro.arb ' +
      'together, run `flutter gen-l10n`, and check that untranslated.txt is empty ' +
      '(CLAUDE.md: never hand-edit generated files).';
  }
  return path + ' is generated by build_runner. Edit the source (table, DAO or model) and run ' +
    '`dart run build_runner build --delete-conflicting-outputs` ' +
    '(CLAUDE.md: never hand-edit generated files).';
}

function judgeFile(input) {
  const path = String(input.file_path || input.notebook_path || '');
  return GENERATED.test(path) ? generatedReason(path) : null;
}

function inPlaceEdit(tokens) {
  const i = tokens.findIndex((t) => SED_OR_PERL.test(t));
  if (i < 0) return null;
  for (const t of tokens.slice(i + 1)) {
    if (t === '--') break;
    if (/^--in-place/.test(t) || /^-[a-zA-Z0-9]*i/.test(t)) {
      return 'In-place sed/perl is banned here: a `perl -i` once emptied an ARB and Git Bash hides ' +
        'the CRLF. Make the change with Read/Edit/Write (or a heredoc to a new file), and check ' +
        "line endings first with `tr -cd '\\r' | wc -c`.";
    }
  }
  return null;
}

function flutterAnalyze(tokens) {
  const i = tokens.findIndex((t) => FLUTTER.test(t));
  if (i < 0 || tokens[i + 1] !== 'analyze') return null;
  return 'Run `dart analyze lib` instead (CLAUDE.md: never `flutter analyze` on the whole workspace).';
}

function sweepingAdd(tokens) {
  const g = tokens.findIndex((t) => GIT.test(t));
  if (g < 0) return null;
  let i = g + 1;
  while (i < tokens.length && tokens[i].startsWith('-')) {
    if (tokens[i] === '-C' || tokens[i] === '-c') i += 2;
    else i += 1;
  }
  if (tokens[i] !== 'add') return null;
  const args = tokens.slice(i + 1);
  if (args.some((a) => a === '--dry-run' || /^-[a-zA-Z]*n/.test(a))) return null;
  const sweep = args.some((a) =>
    a === '--all' || a === '--update' || a === '.' || a === './' || a === '*' ||
    a === ':/' || a === ':/.' || /^-[a-zA-Z]*[Au]/.test(a));
  if (!sweep) return null;
  return 'Stage named paths (`git add <file> ...`), never a sweep: the owner commits, and -A/-u/`.` ' +
    "pulls another agent's half-built files into the commit (the ready-commit rule).";
}

function generatedTarget(tokens) {
  const WRITERS = /^(tee|Set-Content|Out-File|Add-Content|Copy-Item|Move-Item|cp|mv|copy|move)$/i;
  const AFTER = /^(\d?>>?|-o|-Path|-FilePath|-LiteralPath|-Destination)$/i;
  const w = tokens.findIndex((t) => WRITERS.test(t));
  for (let k = 0; k < tokens.length; k++) {
    const t = tokens[k];
    const redirected = t.replace(/^\d?>>?/, '');
    if (redirected !== t && GENERATED.test(redirected)) return generatedReason(redirected);
    if (!GENERATED.test(t)) continue;
    if (k > 0 && AFTER.test(tokens[k - 1])) return generatedReason(t);
    if (w >= 0 && k > w) return generatedReason(t);
  }
  return null;
}

function backgroundSuite(segment, tokens, background) {
  const i = tokens.findIndex((t, k) => FLUTTER_OR_DART.test(t) && tokens[k + 1] === 'test');
  if (i < 0) return null;
  const launcher = tokens.slice(0, i).some((t) => /^(nohup|setsid|start|Start-Job|Start-Process)$/i.test(t));
  const trailingAmp = /(^|[^&])&\s*$/.test(segment);
  if (!background && !launcher && !trailingAmp) return null;
  return 'Never run `flutter test` in the background: a runner that hangs on a timed-out test never ' +
    'exits and the harness waits on it for hours (2026-10-30). The whole suite takes about four ' +
    'minutes here. Run it in the foreground with a timeout of up to 600000 ms, one run at a time on ' +
    'this tree, and never beside a QA `flutter run`.';
}

function judgeShell(input) {
  const command = String(input.command || '');
  if (!command.trim()) return null;
  const background = input.run_in_background === true;
  for (const raw of command.split(/\|\||&&|\||;|\r?\n/)) {
    const segment = raw.trim();
    if (!segment) continue;
    const tokens = segment.split(/\s+/).map(stripQuotes).filter(Boolean);
    const reason = inPlaceEdit(tokens) || flutterAnalyze(tokens) || sweepingAdd(tokens) ||
      generatedTarget(tokens) || backgroundSuite(segment, tokens, background);
    if (reason) return reason;
  }
  return null;
}

function judge(hook) {
  const tool = String(hook.tool_name || '');
  const input = hook.tool_input && typeof hook.tool_input === 'object' ? hook.tool_input : {};
  if (FILE_TOOLS.has(tool)) return judgeFile(input);
  if (SHELL_TOOLS.has(tool)) return judgeShell(input);
  return null;
}

const chunks = [];
process.stdin.on('data', (c) => chunks.push(c));
process.stdin.on('end', () => {
  let reason = null;
  try {
    reason = judge(JSON.parse(Buffer.concat(chunks).toString('utf8')));
  } catch (_) {
    reason = null;
  }
  if (reason) {
    process.stdout.write(JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason: reason,
      },
    }));
  }
  process.exitCode = 0;
});
